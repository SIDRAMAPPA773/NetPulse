const mongoose = require('mongoose');

const metricSchema = new mongoose.Schema({
  device: { type: mongoose.Schema.Types.ObjectId, ref: 'Device', required: true },
  deviceId: { type: mongoose.Schema.Types.ObjectId, ref: 'Device' },
  metricSchemaVersion: { type: Number, default: 3 },
  interfaceId: { type: String },
  latency: { type: Number, default: null },
  rttMin: { type: Number, default: null },
  rttMax: { type: Number, default: null },
  rttStddev: { type: Number, default: null },
  jitter: { type: Number, default: null },
  packetLoss: { type: Number, default: null },
  availability: { type: Number, default: null },
  status: { type: String, enum: ['UP', 'DOWN', 'WARNING', 'UNREACHABLE', 'UNKNOWN'] },
  cpuUtilization: { type: Number, default: null },
  memoryUtilization: { type: Number, default: null },
  incomingTraffic: { type: Number, default: null },
  outgoingTraffic: { type: Number, default: null },
  incomingThroughputBps: { type: Number, default: null },
  outgoingThroughputBps: { type: Number, default: null },
  inboundPacketRate: { type: Number, default: null },
  outboundPacketRate: { type: Number, default: null },
  metricName: { type: String },
  value: { type: Number },
  unit: { type: String },
  numericValue: { type: Number },
  sourceProtocol: { type: String },
  source: { type: String },
  measurementSource: { type: String, enum: ['real', 'simulated'] },
  monitoringMode: { type: String, enum: ['real', 'simulation', 'simulated'] },
  availabilityStatus: { type: String, enum: ['available', 'unavailable', 'unknown'] },
  validity: { type: String, enum: ['valid', 'invalid', 'unknown'] },
  collectionStatus: { type: String, enum: ['success', 'timeout', 'unreachable', 'unsupported', 'error', 'simulated', 'blocked'] },
  errorMessage: { type: String },
  reasonUnavailable: { type: String },
  observationWindowStart: { type: Date },
  observationWindowEnd: { type: Date },
  sampleCount: { type: Number },
  reachability: {
    confirmedMethod: { type: String },
    isReachable: { type: Boolean },
    methodsChecked: [{ type: String }],
    methodsResponding: [{ type: String }],
    reason: { type: String },
  },
  hardware: {
    availability: { type: mongoose.Schema.Types.Mixed },
    cpu: {
      utilization: { type: Number, default: null },
      load: { type: Number, default: null },
      perCore: [{ type: Number }],
      source: { type: String },
      reason: { type: String },
    },
    memory: {
      totalBytes: { type: Number, default: null },
      usedBytes: { type: Number, default: null },
      freeBytes: { type: Number, default: null },
      utilization: { type: Number, default: null },
      source: { type: String },
      reason: { type: String },
    },
    system: {
      sysDescr: { type: String, default: null },
      sysUpTime: { type: Number, default: null },
      sysName: { type: String, default: null },
      sysLocation: { type: String, default: null },
    },
    temperature: {
      celsius: { type: Number, default: null },
      thresholdCelsius: { type: Number, default: null },
      source: { type: String },
      reason: { type: String },
    },
  },
  health: {
    overallScore: { type: Number, default: null },
    healthStatus: { type: String, default: 'Unknown' },
    availabilityScore: { type: Number, default: null },
    performanceScore: { type: Number, default: null },
    trafficScore: { type: Number, default: null },
    hardwareScore: { type: Number, default: null },
    breakdown: [{ type: mongoose.Schema.Types.Mixed }],
  },
  tcp: {
    reachable: { type: Boolean },
    testedPorts: { type: Number },
    openPorts: [{ type: Number }],
    responseTimeMs: { type: Number, default: null },
    results: [{ type: mongoose.Schema.Types.Mixed }],
  },
  dns: {
    hostname: { type: String, default: null },
    status: { type: String, default: null },
    responseTimeMs: { type: Number, default: null },
    errorReason: { type: String, default: null },
  },
  snmp: {
    supported: { type: Boolean },
    responded: { type: Boolean },
    countersSupported: { type: Boolean },
    highCapacitySupported: { type: Boolean },
    reason: { type: String },
    sysUpTime: { type: Number, default: null },
    ifIndex: { type: Number, default: null },
    interfaceName: { type: String, default: null },
    inOctets: { type: Number, default: null },
    outOctets: { type: Number, default: null },
    inOctetsHC: { type: String, default: null },
    outOctetsHC: { type: String, default: null },
    inDelta: { type: Number, default: null },
    outDelta: { type: Number, default: null },
    elapsedSeconds: { type: Number, default: null },
    inBps: { type: Number, default: null },
    outBps: { type: Number, default: null },
    inPackets: { type: Number, default: null },
    outPackets: { type: Number, default: null },
    inPacketsHC: { type: String, default: null },
    outPacketsHC: { type: String, default: null },
    inErrors: { type: Number, default: null },
    outErrors: { type: Number, default: null },
    inDiscards: { type: Number, default: null },
    outDiscards: { type: Number, default: null },
    interfaceSpeed: { type: Number, default: null },
    interfaceHighSpeedMbps: { type: Number, default: null },
    operationalStatus: { type: Number, default: null },
    inPacketsPerSecond: { type: Number, default: null },
    outPacketsPerSecond: { type: Number, default: null },
    counterReset: { type: Boolean, default: false },
    errorCode: { type: String },
    oidChecks: [{ type: mongoose.Schema.Types.Mixed }],
  },
  telemetryChecks: [{ type: mongoose.Schema.Types.Mixed }],
  raw: { type: mongoose.Schema.Types.Mixed },
  derived: { type: mongoose.Schema.Types.Mixed },
  metadata: { type: mongoose.Schema.Types.Mixed },
}, { timestamps: true });

metricSchema.index({ device: 1, createdAt: -1 });
metricSchema.index({ deviceId: 1, createdAt: -1 });
metricSchema.index({ metricName: 1, createdAt: -1 });
metricSchema.index({ createdAt: -1 });
metricSchema.index({ measurementSource: 1, createdAt: -1 });
metricSchema.index({ metricSchemaVersion: 1, createdAt: -1 });

module.exports = mongoose.model('Metric', metricSchema);
